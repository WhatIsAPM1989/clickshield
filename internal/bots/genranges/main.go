// Command genranges downloads the IP ranges that crawler operators publish
// and writes them to ranges.go. Run it with "go generate ./internal/bots".
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"net/netip"
	"os"
	"slices"
	"strings"
	"time"
)

// Each list maps to a catalog bot. The order matters only for overlapping
// prefixes: the first list wins.
var sources = []struct{ bot, url string }{
	{"Bingbot", "https://www.bing.com/toolbox/bingbot.json"},
	{"Googlebot", "https://developers.google.com/static/search/apis/ipranges/googlebot.json"},
	{"Google (спецкраулеры)", "https://developers.google.com/static/search/apis/ipranges/special-crawlers.json"},
	{"Google (по запросу пользователя)", "https://developers.google.com/static/search/apis/ipranges/user-triggered-fetchers-google.json"},
	{"Google (по запросу пользователя)", "https://developers.google.com/static/search/apis/ipranges/user-triggered-fetchers.json"},
	{"OAI-SearchBot", "https://openai.com/searchbot.json"},
	{"GPTBot", "https://openai.com/gptbot.json"},
	{"ChatGPT-User", "https://openai.com/chatgpt-user.json"},
	{"PerplexityBot", "https://www.perplexity.com/perplexitybot.json"},
	{"PerplexityBot", "https://www.perplexity.com/perplexity-user.json"},
	{"Applebot", "https://search.developer.apple.com/applebot.json"},
	{"DuckDuckBot", "https://duckduckgo.com/duckduckbot.json"},
}

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by genranges; DO NOT EDIT.\n\npackage bots\n\n")
	fmt.Fprintf(&b, "// Fetched %s.\nvar publishedRanges = []struct{ bot, prefix string }{\n", time.Now().UTC().Format("2006-01-02"))
	seen := map[netip.Prefix]bool{}
	for _, s := range sources {
		prefixes, err := fetch(s.url)
		if err != nil {
			log.Fatalf("%s: %v", s.url, err)
		}
		fmt.Fprintf(&b, "\t// %s\n", s.url)
		for _, p := range prefixes {
			if !seen[p] {
				seen[p] = true
				fmt.Fprintf(&b, "\t{%q, %q},\n", s.bot, p)
			}
		}
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err = os.WriteFile("ranges.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func fetch(url string) ([]netip.Prefix, error) {
	req, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "clickshield-genranges")
	res, err := (&http.Client{Timeout: 30 * time.Second}).Do(req)
	if err != nil {
		return nil, err
	}
	defer res.Body.Close()
	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("status %s", res.Status)
	}
	var doc struct {
		Prefixes []struct {
			IPv4 string `json:"ipv4Prefix"`
			IPv6 string `json:"ipv6Prefix"`
		} `json:"prefixes"`
	}
	if err = json.NewDecoder(res.Body).Decode(&doc); err != nil {
		return nil, err
	}
	var out []netip.Prefix
	for _, x := range doc.Prefixes {
		for _, s := range []string{x.IPv4, x.IPv6} {
			if s == "" {
				continue
			}
			p, err := netip.ParsePrefix(s)
			if err != nil {
				return nil, err
			}
			out = append(out, p.Masked())
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no prefixes")
	}
	slices.SortFunc(out, func(a, b netip.Prefix) int {
		if c := a.Addr().Compare(b.Addr()); c != 0 {
			return c
		}
		return a.Bits() - b.Bits()
	})
	return out, nil
}

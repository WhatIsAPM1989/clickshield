ALTER TABLE raw_events RENAME TO raw_events_legacy;

CREATE TABLE raw_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    project_id uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    session_id uuid NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    batch_id uuid NOT NULL,
    event_index integer NOT NULL,
    event_time timestamptz NOT NULL,
    event_type text NOT NULL,
    payload jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY(id,created_at)
) PARTITION BY RANGE(created_at);

-- Global batch idempotency lives in ingest_batches, independently of partitions.
CREATE INDEX raw_events_partition_session_idx ON raw_events(session_id,event_time,id);

DO $$
DECLARE day date;
BEGIN
    FOR day IN
        SELECT DISTINCT (created_at AT TIME ZONE 'UTC')::date FROM raw_events_legacy
        UNION SELECT (now() AT TIME ZONE 'UTC')::date + n FROM generate_series(-1,7) n
    LOOP
        EXECUTE format('CREATE TABLE raw_events_%s PARTITION OF raw_events FOR VALUES FROM (%L) TO (%L)',
            to_char(day,'YYYYMMDD'),day::text||' 00:00:00+00',(day+1)::text||' 00:00:00+00');
    END LOOP;
END $$;

INSERT INTO raw_events(id,project_id,session_id,batch_id,event_index,event_time,event_type,payload,created_at)
SELECT id,project_id,session_id,batch_id,event_index,event_time,event_type,payload,created_at FROM raw_events_legacy;
SELECT setval(pg_get_serial_sequence('raw_events','id'),COALESCE(max(id),1),max(id) IS NOT NULL) FROM raw_events;
DROP TABLE raw_events_legacy;
